import { it, expect, vi, afterEach } from "vitest";
import { fixture, input, deferred } from "./bookingFixture";
import { reservationResponse, createFixtureFetch } from "../../../tests/contracts/fixtures";
afterEach(() => vi.useRealTimers());
it("refreshes holds independently and stops only the selected instance", async () => {
  vi.useFakeTimers();
  const a = await fixture();
  const b = await fixture();
  await a.calendar.actions.reserve(input);
  await b.calendar.actions.reserve(input);
  a.calendar.actions.stopReservationRefresh();
  await vi.advanceTimersByTimeAsync(900000);
  expect(a.fetcher.mock.calls.some((c) => String(c[0]).endsWith("/refresh"))).toBe(false);
  expect(b.fetcher.mock.calls.filter((c) => String(c[0]).endsWith("/refresh"))).toHaveLength(1);
  await a.calendar.dispose();
  await b.calendar.dispose();
});
it("disposal detaches immediately while a mutation settles", async () => {
  const gate = deferred<Response>();
  const transport = createFixtureFetch();
  const { calendar } = await fixture({ fetch: (url, init) => (String(url).endsWith("/reservations") ? gate.promise : transport(url, init)) });
  const listener = vi.fn();
  calendar.subscribe(listener);
  const pending = calendar.actions.submit(input);
  const disposing = calendar.dispose();
  const calls = listener.mock.calls.length;
  await expect(calendar.actions.cancel()).rejects.toMatchObject({ code: "disposed" });
  gate.resolve(Response.json(reservationResponse));
  await pending;
  await disposing;
  expect(calendar.getSnapshot().phase).toBe("disposed");
  expect(listener).toHaveBeenCalledTimes(calls);
});
it("keeps hold refresh on rejected cancellation and never overlaps renewal", async () => {
  vi.useFakeTimers();
  const gate = deferred<Response>();
  const transport = createFixtureFetch();
  const { calendar, fetcher } = await fixture({
    fetch: (url, init) => (String(url).endsWith("/refresh") ? gate.promise : init?.method === "DELETE" ? Promise.resolve(Response.json({ success: false })) : transport(url, init)),
  });
  await calendar.actions.reserve(input);
  await expect(calendar.actions.cancel()).rejects.toThrow();
  expect(calendar.getSnapshot().phase).toBe("recovery-required");
  await vi.advanceTimersByTimeAsync(900000);
  expect(fetcher.mock.calls.filter((c) => String(c[0]).endsWith("/refresh"))).toHaveLength(1);
  await vi.advanceTimersByTimeAsync(10000);
  expect(fetcher.mock.calls.filter((c) => String(c[0]).endsWith("/refresh"))).toHaveLength(1);
  gate.resolve(Response.json({ success: true, data: [] }));
  await vi.advanceTimersByTimeAsync(0);
  await calendar.dispose();
  expect(vi.getTimerCount()).toBe(0);
});
it("renewal failure blocks checkout and retains recovery", async () => {
  vi.useFakeTimers();
  const transport = createFixtureFetch();
  const { calendar, fetcher } = await fixture({ fetch: (url, init) => (String(url).endsWith("/refresh") ? Promise.resolve(Response.json({ success: false })) : transport(url, init)) });
  await calendar.actions.reserve(input);
  await vi.advanceTimersByTimeAsync(900000);
  expect(calendar.getSnapshot().phase).toBe("recovery-required");
  await expect(calendar.actions.confirm()).rejects.toMatchObject({ code: "recovery-required" });
  expect(fetcher.mock.calls.some((c) => String(c[0]).endsWith("/confirm"))).toBe(false);
  await calendar.dispose();
});
it("bounds disposal of a lost mutation and ignores the late response", async () => {
  vi.useFakeTimers();
  const gate = deferred<Response>();
  const transport = createFixtureFetch();
  const { calendar } = await fixture({ fetch: (url, init) => (String(url).endsWith("/reservations") ? gate.promise : transport(url, init)) });
  const pending = calendar.actions.submit(input);
  const rejection = expect(pending).rejects.toMatchObject({ code: "recovery-required" });
  const disposal = calendar.dispose();
  await vi.advanceTimersByTimeAsync(30000);
  await rejection;
  await disposal;
  expect(calendar.getSnapshot().phase).toBe("disposed");
  expect(calendar.getSnapshot().recovery?.operation).toBe("submit");
  const revision = calendar.getSnapshot().revision;
  gate.resolve(Response.json(reservationResponse));
  await vi.advanceTimersByTimeAsync(0);
  expect(calendar.getSnapshot().revision).toBe(revision);
  expect(vi.getTimerCount()).toBe(0);
});
it("bounds payment confirmation at five minutes without retry or late success", async () => {
  vi.useFakeTimers();
  const gate = deferred<any>();
  const payment = { confirm: vi.fn(() => gate.promise) };
  const { calendar } = await fixture({ paid: true, payment });
  const pending = calendar.actions.submit(input);
  const rejection = expect(pending).rejects.toMatchObject({ code: "recovery-required" });
  await vi.advanceTimersByTimeAsync(300000);
  await rejection;
  expect(calendar.getSnapshot().recovery?.paymentStatus).toBe("unknown");
  gate.resolve({ status: "succeeded", paymentIntentId: "pi_test" });
  await vi.advanceTimersByTimeAsync(0);
  expect(calendar.getSnapshot().phase).toBe("recovery-required");
  expect(payment.confirm).toHaveBeenCalledTimes(1);
  await calendar.dispose();
});
it("keeps refresh alive during disposal until an active confirmation settles", async () => {
  vi.useFakeTimers();
  const gate = deferred<Response>();
  const transport = createFixtureFetch();
  const { calendar, fetcher } = await fixture({ fetch: (url, init) => (String(url).endsWith("/confirm") ? gate.promise : transport(url, init)) });
  await calendar.actions.reserve(input);
  await vi.advanceTimersByTimeAsync(890000);
  const pending = calendar.actions.confirm();
  const disposal = calendar.dispose();
  await vi.advanceTimersByTimeAsync(10000);
  expect(fetcher.mock.calls.filter((c) => String(c[0]).endsWith("/refresh"))).toHaveLength(1);
  gate.resolve(Response.json(reservationResponse));
  await pending;
  await disposal;
  expect(calendar.getSnapshot().phase).toBe("disposed");
  expect(vi.getTimerCount()).toBe(0);
});
it("clears a held reservation timer on identity reset", async () => {
  vi.useFakeTimers();
  const { calendar, fetcher } = await fixture();
  await calendar.actions.reserve(input);
  await calendar.actions.setConfig({ token: "new-calendar" });
  await vi.advanceTimersByTimeAsync(900000);
  expect(fetcher.mock.calls.some((c) => String(c[0]).endsWith("/refresh"))).toBe(false);
  expect(calendar.getSnapshot().reservationUuid).toBeUndefined();
  await calendar.dispose();
});
it("successful explicit cancellation clears the hold only after valid success", async () => {
  vi.useFakeTimers();
  const { calendar, fetcher } = await fixture();
  await calendar.actions.reserve(input);
  expect(await calendar.actions.cancel()).toBe(true);
  expect(calendar.getSnapshot().reservationUuid).toBeUndefined();
  await vi.advanceTimersByTimeAsync(900000);
  expect(fetcher.mock.calls.some((c) => String(c[0]).endsWith("/refresh"))).toBe(false);
  await calendar.dispose();
});
